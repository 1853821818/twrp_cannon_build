#!/usr/bin/env python3
"""Trim libinit dependencies that are unavailable in the TWRP minimal tree.

- `apex-info-list` is generated by system/apex/apexd, which the workflow
  removes. Recovery does not use it, so drop the generated source reference.
- `libxml2` is only used by `#ifndef RECOVERY` code in init.cpp and is not in
  the minimal manifest. Drop it from the shared init static library list for
  this recovery-only build.
"""
from pathlib import Path

p = Path("system/core/init/Android.bp")
s = p.read_text()
changed = []

old_gen = '''    generated_sources: [
        "apex-info-list",
    ],
'''
if old_gen in s:
    s = s.replace(old_gen, "", 1)
    changed.append("generated_sources")

old_exclude = '''            exclude_generated_sources: [
                "apex-info-list",
            ],
'''
if old_exclude in s:
    s = s.replace(old_exclude, "", 1)
    changed.append("exclude_generated_sources")

old_xml = '        "libxml2",\n'
if old_xml in s:
    s = s.replace(old_xml, "", 1)
    changed.append("libxml2")

# 精简树的 libinit 由 Make 以默认变体拉入，不会自动带 recovery 变体的
# -DRECOVERY；init.cpp 在非 RECOVERY 下会 include 由已删除 apexd 生成的
# com_android_apex.h。显式给 libinit 加 -DRECOVERY，走 recovery 分支。
libinit_marker = 'cc_library_static {\n    name: "libinit",'
libinit_with_flag = libinit_marker + '\n    cflags: ["-DRECOVERY"],'
if libinit_marker in s and libinit_with_flag not in s:
    s = s.replace(libinit_marker, libinit_with_flag, 1)
    changed.append("recovery_flag")

p.write_text(s)
print("LIBINIT_RECOVERY_TRIMMED " + ",".join(changed) if changed else "LIBINIT_PATTERN_NOT_FOUND")
